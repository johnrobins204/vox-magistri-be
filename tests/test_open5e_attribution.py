"""SPEC-0012 WP-3: attribution generation and the OGL gate.

Every input is built under tmp_path. The OGL source path is monkeypatched to a fixture,
so the real scripts/licenses/OGL-1.0a.txt (supplied by the human) is never read.
"""

import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "ingest_open5e.py"

_spec = importlib.util.spec_from_file_location("ingest_open5e", SCRIPT)
ingest_open5e = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ingest_open5e)

SRD_2014 = "srd-2014"
SRD_2024 = "srd-2024"
THIRD_PARTY = "a5e-ag"
CC = "CC-BY-4.0"
OGL = "Open Game License 1.0a"


def _licenses(license_text: str | None) -> list[dict] | None:
    """Live shape: a list of {name, key}; "" gives an empty list, None gives null."""
    if license_text is None:
        return None
    if license_text == "":
        return []
    return [{"name": license_text, "key": license_text.lower().replace(" ", "-")}]


def _document(key: str, license_text: str | None, display: str | None = None) -> dict:
    return {
        "key": key,
        "name": f"Document {key}",
        "display_name": display or f"Title {key}",
        "publisher": {"name": f"Publisher of {key}", "key": f"pub-{key}"},
        "gamesystem": {"name": "5e", "key": "5e"},
        "permalink": f"https://example.invalid/{key}",
        "licenses": _licenses(license_text),
    }


def _weapon(name: str, document: dict) -> dict:
    doc = {k: v for k, v in document.items() if k != "licenses"}
    return {
        "key": f"{document['key']}_{name.lower().replace(' ', '-')}",
        "name": name,
        "document": doc,
        "properties": [{"property": {"name": "Light", "type": None, "desc": "d"}, "detail": None}],
        "damage_type": {"name": "Piercing", "key": "piercing"},
        "damage_dice": "1d6",
        "distance_unit": "feet",
        "range": 0,
        "long_range": 0,
        "is_simple": True,
        "is_improvised": False,
    }


@pytest.fixture
def paths(monkeypatch, tmp_path):
    monkeypatch.setattr(ingest_open5e, "OVERLAY_DIR", tmp_path / "no-overlays")
    monkeypatch.setattr(ingest_open5e, "OGL_LICENSE_SOURCE", tmp_path / "licenses" / "OGL.txt")
    snap = tmp_path / "snap"
    snap.mkdir()
    out_dir = tmp_path / "reference"
    out_dir.mkdir()
    return snap, out_dir / "weapons.json"


def _snapshot(snap: Path, documents: list[dict], entries: list[dict]) -> None:
    (snap / "_documents.json").write_text(json.dumps(documents), encoding="utf-8")
    (snap / "weapons.json").write_text(json.dumps(entries), encoding="utf-8")


def test_t21_attribution_has_one_section_per_used_document(tmp_path):
    documents = {
        SRD_2014: _document(SRD_2014, CC, "SRD 5.1"),
        SRD_2024: _document(SRD_2024, CC, "SRD 5.2"),
        THIRD_PARTY: _document(THIRD_PARTY, CC, "Third Party Book"),
    }
    out = tmp_path / "ATTRIBUTION.md"

    text = ingest_open5e.write_attribution(documents, [SRD_2024, SRD_2014], out)

    assert out.read_text(encoding="utf-8") == text
    assert text.count("\n## ") == 2
    assert "Generated by scripts/ingest_open5e.py" in text
    assert "Do not edit by hand" in text
    assert "Third Party Book" not in text
    for key, title in ((SRD_2014, "SRD 5.1"), (SRD_2024, "SRD 5.2")):
        assert f"## {title}" in text
        assert f"- Publisher: Publisher of {key}" in text
        assert f"- License: {CC}" in text
        assert f"- Permalink: https://example.invalid/{key}" in text
    assert text.count("- Third-party: no") == 2


def test_t21_third_party_section_is_marked(tmp_path):
    documents = {THIRD_PARTY: _document(THIRD_PARTY, CC, "Third Party Book")}

    text = ingest_open5e.write_attribution(documents, [THIRD_PARTY], tmp_path / "A.md")

    assert "## Third Party Book" in text
    assert "- Third-party: yes" in text


def test_t21_ingest_writes_attribution_for_used_documents_only(paths, monkeypatch):
    snap, out = paths
    monkeypatch.setitem(
        ingest_open5e.DOCUMENT_ALLOWLIST, "weapons", [SRD_2014, SRD_2024, THIRD_PARTY]
    )
    srd_2024 = _document(SRD_2024, CC, "SRD 5.2")
    documents = [
        _document(SRD_2014, CC),
        srd_2024,
        _document(THIRD_PARTY, CC, "Third Party Book"),
    ]
    entries = [
        _weapon("Longsword", srd_2024),
        _weapon("Shortbow", documents[2]),
    ]
    _snapshot(snap, documents, entries)

    ingest_open5e.ingest("weapons", snap, out)

    text = (out.parent / "ATTRIBUTION.md").read_text(encoding="utf-8")
    assert "## SRD 5.2" in text
    assert "## Third Party Book" in text
    assert "Title srd-2014" not in text
    assert "- Third-party: yes" in text


def test_t22_ogl_document_without_license_file_fails_before_writing(paths, monkeypatch):
    snap, out = paths
    monkeypatch.setitem(
        ingest_open5e.DOCUMENT_ALLOWLIST, "weapons", [SRD_2014, SRD_2024, THIRD_PARTY]
    )
    srd_2024 = _document(SRD_2024, CC)
    documents = [_document(SRD_2014, CC), srd_2024, _document(THIRD_PARTY, OGL)]
    _snapshot(snap, documents, [_weapon("Longsword", srd_2024)])

    with pytest.raises(FileNotFoundError, match=THIRD_PARTY):
        ingest_open5e.ingest("weapons", snap, out)

    assert not out.exists()
    assert not (out.parent / "ATTRIBUTION.md").exists()
    assert not (out.parent / "LICENSE-OGL.txt").exists()


def test_t22_ogl_license_file_is_copied_when_present(paths, monkeypatch):
    snap, out = paths
    monkeypatch.setitem(
        ingest_open5e.DOCUMENT_ALLOWLIST, "weapons", [SRD_2014, SRD_2024, THIRD_PARTY]
    )
    srd_2024 = _document(SRD_2024, CC)
    documents = [_document(SRD_2014, CC), srd_2024, _document(THIRD_PARTY, OGL)]
    _snapshot(snap, documents, [_weapon("Longsword", srd_2024)])
    source = ingest_open5e.OGL_LICENSE_SOURCE
    source.parent.mkdir(parents=True)
    source.write_bytes(b"OGL FIXTURE TEXT\n")

    ingest_open5e.ingest("weapons", snap, out)

    assert (out.parent / "LICENSE-OGL.txt").read_bytes() == b"OGL FIXTURE TEXT\n"


