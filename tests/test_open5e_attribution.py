def test_t21_rewrite_keeps_sections_of_other_documents(tmp_path):
    out = tmp_path / "ATTRIBUTION.md"
    documents = {
        SRD_2014: _document(SRD_2014, CC, "SRD 5.1"),
        SRD_2024: _document(SRD_2024, CC, "SRD 5.2"),
        THIRD_PARTY: _document(THIRD_PARTY, CC, "Third Party Book"),
    }
    ingest_open5e.write_attribution(documents, [SRD_2014, SRD_2024], out)

    ingest_open5e.write_attribution(documents, [THIRD_PARTY], out)

    text = out.read_text(encoding="utf-8")
    assert "## SRD 5.1" in text
    assert "## SRD 5.2" in text
    assert "## Third Party Book" in text
    assert text.count("\n## ") == 3


def test_t21_rewrite_replaces_only_the_rendered_document(tmp_path):
    out = tmp_path / "ATTRIBUTION.md"
    documents = {
        SRD_2014: _document(SRD_2014, CC, "SRD 5.1"),
        SRD_2024: _document(SRD_2024, CC, "SRD 5.2"),
        THIRD_PARTY: _document(THIRD_PARTY, CC, "Third Party Book"),
    }
    ingest_open5e.write_attribution(documents, [SRD_2014, SRD_2024, THIRD_PARTY], out)

    documents[SRD_2024] = _document(SRD_2024, CC, "SRD 5.2 (revised)")
    ingest_open5e.write_attribution(documents, [SRD_2024], out)

    text = out.read_text(encoding="utf-8")
    assert "## SRD 5.2 (revised)" in text
    assert "## SRD 5.2\n" not in text
    assert "## SRD 5.1" in text
    assert "## Third Party Book" in text
    assert text.count("\n## ") == 3


def test_t21_repeated_rewrite_is_byte_identical(tmp_path):
    out = tmp_path / "ATTRIBUTION.md"
    documents = {
        SRD_2014: _document(SRD_2014, CC, "SRD 5.1"),
        THIRD_PARTY: _document(THIRD_PARTY, CC, "Third Party Book"),
    }
    ingest_open5e.write_attribution(documents, [SRD_2014], out)
    ingest_open5e.write_attribution(documents, [THIRD_PARTY], out)
    first = out.read_bytes()

    ingest_open5e.write_attribution(documents, [THIRD_PARTY], out)

    assert out.read_bytes() == first
